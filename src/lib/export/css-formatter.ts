// CSS Custom Properties formatter
// Outputs all tokens as :root CSS variables

import type { DesignTokens } from "../tokens/types";

export function formatCSS(tokens: DesignTokens, systemName?: string): string {
  const name = systemName || tokens.meta.name;
  const lines: string[] = [];

  lines.push(`/* ${name} — CSS Custom Properties */`);
  lines.push(`/* Generated by DS.ai */`);
  lines.push("");
  lines.push(":root {");

  // Semantic colors
  lines.push("  /* Semantic Colors */");
  lines.push(`  --background: ${tokens.semantic.background};`);
  lines.push(`  --foreground: ${tokens.semantic.foreground};`);
  lines.push(`  --card: ${tokens.semantic.card};`);
  lines.push(`  --card-foreground: ${tokens.semantic.cardForeground};`);
  lines.push(`  --popover: ${tokens.semantic.popover};`);
  lines.push(`  --popover-foreground: ${tokens.semantic.popoverForeground};`);
  lines.push(`  --primary: ${tokens.semantic.primary};`);
  lines.push(`  --primary-foreground: ${tokens.semantic.primaryForeground};`);
  lines.push(`  --secondary: ${tokens.semantic.secondary};`);
  lines.push(`  --secondary-foreground: ${tokens.semantic.secondaryForeground};`);
  lines.push(`  --muted: ${tokens.semantic.muted};`);
  lines.push(`  --muted-foreground: ${tokens.semantic.mutedForeground};`);
  lines.push(`  --accent: ${tokens.semantic.accent};`);
  lines.push(`  --accent-foreground: ${tokens.semantic.accentForeground};`);
  lines.push(`  --destructive: ${tokens.semantic.destructive};`);
  lines.push(`  --destructive-foreground: ${tokens.semantic.destructiveForeground};`);
  lines.push(`  --border: ${tokens.semantic.border};`);
  lines.push(`  --input: ${tokens.semantic.input};`);
  lines.push(`  --ring: ${tokens.semantic.ring};`);
  lines.push("");

  // Color scales
  const scaleNames = ["primary", "secondary", "accent", "neutral", "success", "warning", "error", "info"] as const;
  lines.push("  /* Color Scales */");
  for (const scaleName of scaleNames) {
    const scale = tokens.colors[scaleName];
    for (const [shade, value] of Object.entries(scale)) {
      lines.push(`  --color-${scaleName}-${shade}: ${value};`);
    }
  }
  lines.push("");

  // Typography
  lines.push("  /* Typography */");
  lines.push(`  --font-heading: ${tokens.typography.headingFamily};`);
  lines.push(`  --font-body: ${tokens.typography.bodyFamily};`);
  lines.push(`  --font-mono: ${tokens.typography.monoFamily};`);
  lines.push("");

  // Border radius
  lines.push("  /* Border Radius */");
  for (const [key, value] of Object.entries(tokens.borderRadius)) {
    lines.push(`  --radius-${key}: ${value};`);
  }
  lines.push(`  --radius: ${tokens.borderRadius.md};`);
  lines.push("");

  // Shadows
  lines.push("  /* Shadows */");
  for (const [key, value] of Object.entries(tokens.shadows)) {
    if (value !== "none") {
      lines.push(`  --shadow-${key}: ${value};`);
    }
  }
  lines.push("");

  // Animation
  lines.push("  /* Animation */");
  lines.push(`  --duration-fast: ${tokens.animation.duration.fast};`);
  lines.push(`  --duration-normal: ${tokens.animation.duration.normal};`);
  lines.push(`  --duration-slow: ${tokens.animation.duration.slow};`);
  lines.push(`  --ease-in: ${tokens.animation.easing.easeIn};`);
  lines.push(`  --ease-out: ${tokens.animation.easing.easeOut};`);
  lines.push(`  --ease-in-out: ${tokens.animation.easing.easeInOut};`);
  lines.push("");

  // Breakpoints
  lines.push("  /* Breakpoints */");
  for (const [key, value] of Object.entries(tokens.breakpoints)) {
    lines.push(`  --breakpoint-${key}: ${value};`);
  }
  lines.push("");

  // Z-Index
  lines.push("  /* Z-Index */");
  for (const [key, value] of Object.entries(tokens.zIndex)) {
    lines.push(`  --z-${key}: ${value};`);
  }
  lines.push("");

  // Opacity
  lines.push("  /* Opacity */");
  for (const [key, value] of Object.entries(tokens.opacity)) {
    lines.push(`  --opacity-${key}: ${value};`);
  }
  lines.push("");

  // Border Width
  lines.push("  /* Border Width */");
  for (const [key, value] of Object.entries(tokens.borderWidth)) {
    lines.push(`  --border-width-${key}: ${value};`);
  }
  lines.push("");

  // Letter Spacing
  lines.push("  /* Letter Spacing */");
  for (const [key, value] of Object.entries(tokens.letterSpacing)) {
    lines.push(`  --tracking-${key}: ${value};`);
  }
  lines.push("");

  // Line Height
  lines.push("  /* Line Height */");
  for (const [key, value] of Object.entries(tokens.lineHeight)) {
    lines.push(`  --leading-${key}: ${value};`);
  }
  lines.push("");

  // Component Tokens — Button
  lines.push("  /* Component Tokens — Button */");
  lines.push(`  --btn-height-sm: ${tokens.components.button.heightSm};`);
  lines.push(`  --btn-height-md: ${tokens.components.button.heightMd};`);
  lines.push(`  --btn-height-lg: ${tokens.components.button.heightLg};`);
  lines.push(`  --btn-padding-x: ${tokens.components.button.paddingX};`);
  lines.push(`  --btn-padding-x-sm: ${tokens.components.button.paddingXSm};`);
  lines.push(`  --btn-font-size: ${tokens.components.button.fontSize};`);
  lines.push(`  --btn-font-size-sm: ${tokens.components.button.fontSizeSm};`);
  lines.push(`  --btn-font-weight: ${tokens.components.button.fontWeight};`);
  lines.push(`  --btn-letter-spacing: ${tokens.components.button.letterSpacing};`);
  lines.push(`  --btn-text-transform: ${tokens.components.button.textTransform};`);
  lines.push(`  --btn-border-radius: ${tokens.components.button.borderRadius};`);
  lines.push(`  --btn-transition: ${tokens.components.button.transition};`);
  lines.push(`  --btn-hover-transform: ${tokens.components.button.hoverTransform};`);
  lines.push("");

  // Component Tokens — Card
  lines.push("  /* Component Tokens — Card */");
  lines.push(`  --card-padding: ${tokens.components.card.padding};`);
  lines.push(`  --card-padding-sm: ${tokens.components.card.paddingSm};`);
  lines.push(`  --card-border-radius: ${tokens.components.card.borderRadius};`);
  lines.push(`  --card-border-width: ${tokens.components.card.borderWidth};`);
  lines.push("");

  // Component Tokens — Input
  lines.push("  /* Component Tokens — Input */");
  lines.push(`  --input-height: ${tokens.components.input.height};`);
  lines.push(`  --input-padding-x: ${tokens.components.input.paddingX};`);
  lines.push(`  --input-font-size: ${tokens.components.input.fontSize};`);
  lines.push(`  --input-border-radius: ${tokens.components.input.borderRadius};`);
  lines.push(`  --input-border-width: ${tokens.components.input.borderWidth};`);
  lines.push("");

  // Component Tokens — Badge
  lines.push("  /* Component Tokens — Badge */");
  lines.push(`  --badge-padding-x: ${tokens.components.badge.paddingX};`);
  lines.push(`  --badge-padding-y: ${tokens.components.badge.paddingY};`);
  lines.push(`  --badge-font-size: ${tokens.components.badge.fontSize};`);
  lines.push(`  --badge-font-weight: ${tokens.components.badge.fontWeight};`);
  lines.push(`  --badge-border-radius: ${tokens.components.badge.borderRadius};`);
  lines.push(`  --badge-letter-spacing: ${tokens.components.badge.letterSpacing};`);
  lines.push(`  --badge-text-transform: ${tokens.components.badge.textTransform};`);
  lines.push("");

  // Component Tokens — Avatar
  lines.push("  /* Component Tokens — Avatar */");
  lines.push(`  --avatar-size-sm: ${tokens.components.avatar.sizeSm};`);
  lines.push(`  --avatar-size-md: ${tokens.components.avatar.sizeMd};`);
  lines.push(`  --avatar-size-lg: ${tokens.components.avatar.sizeLg};`);
  lines.push(`  --avatar-border-radius: ${tokens.components.avatar.borderRadius};`);
  lines.push("");

  // Typography Usage
  lines.push("  /* Typography Usage */");
  const typoRoles = [
    "display", "h1", "h2", "h3", "h4", "h5", "h6",
    "body", "bodyLarge", "bodySmall", "caption", "button", "label", "overline",
  ] as const;
  for (const role of typoRoles) {
    const rule = tokens.typographyUsage[role];
    const cssRole = role.replace(/([A-Z])/g, "-$1").toLowerCase();
    lines.push(`  --typo-${cssRole}-weight: ${rule.weight};`);
    lines.push(`  --typo-${cssRole}-size: ${rule.size};`);
    lines.push(`  --typo-${cssRole}-line-height: ${rule.lineHeight};`);
    lines.push(`  --typo-${cssRole}-letter-spacing: ${rule.letterSpacing};`);
    if (rule.textTransform) {
      lines.push(`  --typo-${cssRole}-text-transform: ${rule.textTransform};`);
    }
  }
  lines.push("");

  // Focus
  lines.push("  /* Focus */");
  lines.push(`  --focus-ring-width: ${tokens.focus.ringWidth};`);
  lines.push(`  --focus-ring-offset: ${tokens.focus.ringOffset};`);
  lines.push(`  --focus-ring-color: ${tokens.focus.ringColor};`);
  lines.push(`  --focus-outline-style: ${tokens.focus.outlineStyle};`);
  lines.push("");

  // Section Spacing
  lines.push("  /* Section Spacing */");
  lines.push(`  --section-padding-sm: ${tokens.sectionSpacing.paddingSm};`);
  lines.push(`  --section-padding-md: ${tokens.sectionSpacing.paddingMd};`);
  lines.push(`  --section-padding-lg: ${tokens.sectionSpacing.paddingLg};`);
  lines.push(`  --section-padding-sm-tablet: ${tokens.sectionSpacing.paddingSmTablet};`);
  lines.push(`  --section-padding-md-tablet: ${tokens.sectionSpacing.paddingMdTablet};`);
  lines.push(`  --section-padding-lg-tablet: ${tokens.sectionSpacing.paddingLgTablet};`);
  lines.push(`  --section-padding-sm-mobile: ${tokens.sectionSpacing.paddingSmMobile};`);
  lines.push(`  --section-padding-md-mobile: ${tokens.sectionSpacing.paddingMdMobile};`);
  lines.push(`  --section-padding-lg-mobile: ${tokens.sectionSpacing.paddingLgMobile};`);

  lines.push("}");

  return lines.join("\n");
}
