// Client-side ZIP builder using JSZip
// Packages selected format files and triggers browser download

import JSZip from "jszip";
import type { DesignTokens } from "../tokens/types";
import { formatDTCG } from "./dtcg-formatter";
import { formatCSS } from "./css-formatter";
import { formatTailwind } from "./tailwind-formatter";
import { formatFlatJSON } from "./flat-json-formatter";

type FormatId = "dtcg" | "css" | "tailwind" | "json";

const FORMATTERS: Record<FormatId, { fn: (t: DesignTokens, name?: string) => string; filename: string }> = {
  dtcg: { fn: formatDTCG, filename: "tokens.json" },
  css: { fn: formatCSS, filename: "variables.css" },
  tailwind: { fn: formatTailwind, filename: "tailwind-theme.css" },
  json: { fn: formatFlatJSON, filename: "tokens.flat.json" },
};

export async function buildAndDownloadZip(
  tokens: DesignTokens,
  selectedFormats: Set<string>,
  systemName?: string
): Promise<void> {
  const zip = new JSZip();
  const name = systemName || tokens.meta.name;
  const folderName = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  const folder = zip.folder(folderName);

  if (!folder) throw new Error("Failed to create ZIP folder");

  // Add README
  folder.file(
    "README.md",
    [
      `# ${name}`,
      "",
      `> ${tokens.meta.description}`,
      "",
      `**Industry:** ${tokens.meta.industry}`,
      `**Mood:** ${tokens.meta.mood.join(", ")}`,
      `**Generated:** ${tokens.meta.generatedAt || new Date().toISOString()}`,
      "",
      "## Files",
      "",
      ...Array.from(selectedFormats).map((id) => {
        const fmt = FORMATTERS[id as FormatId];
        return fmt ? `- \`${fmt.filename}\` — ${id.toUpperCase()} format` : "";
      }),
      "",
      "---",
      "Generated by [DS.ai](https://ds.ai)",
    ].join("\n")
  );

  // Add quick-start guide
  folder.file(
    "quickstart.md",
    [
      `# ${name} — Quick-Start Guide`,
      "",
      "Get your design system running in under 5 minutes.",
      "",
      "---",
      "",
      "## Next.js + Tailwind CSS v4",
      "",
      "1. Copy `tailwind-theme.css` into your project (e.g. `src/styles/theme.css`).",
      "2. Import it in your main CSS file **after** the Tailwind import:",
      "",
      "```css",
      '/* src/app/globals.css */',
      '@import "tailwindcss";',
      '@import "../styles/theme.css";',
      "```",
      "",
      "3. Use the tokens with Tailwind utilities:",
      "",
      "```html",
      '<div class="bg-background text-foreground font-sans">',
      '  <h1 class="text-primary font-heading text-4xl">Hello</h1>',
      '  <button class="bg-primary text-primary-foreground rounded-md px-4 py-2">',
      "    Click me",
      "  </button>",
      "</div>",
      "```",
      "",
      "---",
      "",
      "## Vanilla CSS",
      "",
      "1. Copy `variables.css` into your project.",
      "2. Import it at the top of your main stylesheet:",
      "",
      "```css",
      '/* styles.css */',
      '@import "./variables.css";',
      "",
      "body {",
      "  background-color: var(--background);",
      "  color: var(--foreground);",
      '  font-family: var(--font-body, system-ui, sans-serif);',
      "}",
      "",
      ".btn-primary {",
      "  background-color: var(--primary);",
      "  color: var(--primary-foreground);",
      "  border-radius: var(--radius-md);",
      "  padding: 0.5rem 1rem;",
      "  border: var(--border-width-default) solid var(--border);",
      "  transition: all var(--duration-fast) var(--ease-in-out);",
      "}",
      "```",
      "",
      "---",
      "",
      "## React + Vite",
      "",
      "1. Copy `variables.css` into `src/`.",
      "2. Import it in your entry point:",
      "",
      "```tsx",
      "// src/main.tsx",
      'import "./variables.css";',
      'import App from "./App";',
      "",
      'ReactDOM.createRoot(document.getElementById("root")!).render(<App />);',
      "```",
      "",
      "3. Reference tokens in your components or CSS modules:",
      "",
      "```tsx",
      "// src/components/Card.tsx",
      "export function Card({ children }: { children: React.ReactNode }) {",
      "  return (",
      "    <div",
      "      style={{",
      '        backgroundColor: "var(--card)",',
      '        color: "var(--card-foreground)",',
      '        borderRadius: "var(--radius-lg)",',
      '        boxShadow: "var(--shadow-md)",',
      '        padding: "1.5rem",',
      '        border: "var(--border-width-thin) solid var(--border)",',
      "      }}",
      "    >",
      "      {children}",
      "    </div>",
      "  );",
      "}",
      "```",
      "",
      "---",
      "",
      "## Using the DTCG JSON",
      "",
      "The `tokens.json` file follows the [W3C Design Token Community Group](https://design-tokens.github.io/community-group/format/) spec.",
      "You can pipe it into tools like [Style Dictionary](https://amzn.github.io/style-dictionary/) to generate platform-specific outputs:",
      "",
      "```bash",
      "npx style-dictionary build --config sd.config.js",
      "```",
      "",
      "## Using the Flat JSON",
      "",
      "`tokens.flat.json` is a simple key-value map with dot-notation paths, ideal for:",
      "- JavaScript/TypeScript runtime consumption",
      "- CMS or database storage",
      "- Programmatic token lookup",
      "",
      "```ts",
      'import tokens from "./tokens.flat.json";',
      "",
      'const primary500 = tokens["color.primary.500"];',
      'const bodyFont = tokens["typography.body-family"];',
      "```",
      "",
      "---",
      "",
      "Generated by [DS.ai](https://ds.ai)",
    ].join("\n")
  );

  // Add each selected format
  for (const formatId of selectedFormats) {
    const formatter = FORMATTERS[formatId as FormatId];
    if (formatter) {
      const content = formatter.fn(tokens, name);
      folder.file(formatter.filename, content);
    }
  }

  // Generate and download
  const blob = await zip.generateAsync({ type: "blob" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${folderName}.zip`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
